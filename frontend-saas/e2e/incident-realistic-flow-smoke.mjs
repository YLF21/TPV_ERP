import assert from "node:assert/strict";
import { spawn } from "node:child_process";
import { mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";
import { setup, assignees, companyId } from "./failure-workflow-fixture.mjs";

const base = "http://127.0.0.1:5201/";
const errors = [];
let browser;
const server = spawn(process.execPath, [fileURLToPath(new URL("../node_modules/vite/bin/vite.js", import.meta.url)), "--host", "127.0.0.1", "--port", "5201", "--strictPort", "--configLoader", "runner"], { cwd: fileURLToPath(new URL("..", import.meta.url)), stdio: "ignore", windowsHide: true });
try {
  for (let i = 0; i < 100; i++) { try { if ((await fetch(base)).ok) break; } catch {} await new Promise(resolve => setTimeout(resolve, 100)); }
  browser = await chromium.launch({ headless: true });
  const { page, state, panel, open } = await setup(browser, errors, base);
  await open("APPLICATION_ERROR");
  await panel.getByLabel("Motivo de la intervención").fill("Cliente solicita ayuda para corregir configuración");
  await panel.getByRole("button", { name: "Derivar a soporte manual", exact: true }).click();
  let workflow = page.getByRole("region", { name: "Seguimiento de la incidencia", exact: true });
  const field = name => workflow.getByLabel(name, { exact: false });
  const button = name => workflow.getByRole("button", { name, exact: true });
  async function ready(name) {
    await button(name).waitFor();
    await page.waitForFunction(name => [...document.querySelectorAll("button")].some(b => b.textContent === name && !b.disabled), name);
  }
  async function act(name, note) {
    await ready(name);
    await field("Nota interna de intervención (obligatoria)").fill(note);
    await button(name).click();
  }
  await act("Trabajar desde SaaS", "Revisar parámetros del cliente desde el panel");
  await ready("Pasar a comprobación");
  assert.equal(state.intervention.status, "SAAS_IN_PROGRESS");
  assert.equal(state.intervention.assigneeUserId, assignees[0].id);
  const solution = "Corregido el perfil de configuración desde SaaS";
  await field("Solución aplicada").fill(solution);
  await field("Nota interna de intervención (obligatoria)").fill("Borrador pendiente de la actuación realizada");
  await field("Responsable asignado").selectOption(assignees[1].id);
  await button("Guardar planificación").click();
  await ready("Pasar a comprobación");
  assert.equal(await field("Solución aplicada").inputValue(), solution, "Saving planning preserves unsent solution");
  assert.equal(await field("Nota interna de intervención (obligatoria)").inputValue(), "Borrador pendiente de la actuación realizada");
  assert.equal(state.intervention.assigneeUserId, assignees[1].id);
  await page.getByRole("button", { name: "Cerrar detalle", exact: true }).click();
  await open("APPLICATION_ERROR"); await ready("Pasar a comprobación");
  assert.equal(await field("Solución aplicada").inputValue(), solution, "Draft survives closing and reopening the failure");
  const beforeWait = state.interventionPosts.length;
  await act("Esperar al cliente", "Cliente no puede comprobarlo hasta mañana");
  assert.equal(state.interventionPosts.length, beforeWait, "Waiting requires a review date");
  await field("Próxima revisión (para dejar en espera)").fill("2020-01-01T10:00");
  await button("Esperar al cliente").click();
  assert.equal(state.interventionPosts.length, beforeWait, "Past review date is rejected");
  await field("Próxima revisión (para dejar en espera)").fill("2099-01-01T10:00");
  await button("Esperar al cliente").click(); await ready("Retomar trabajo");
  assert.equal(state.intervention.resumeStatus, "SAAS_IN_PROGRESS");
  await act("Retomar trabajo", "Cliente disponible para realizar la prueba"); await ready("Pasar a comprobación");
  assert.equal(await field("Solución aplicada").inputValue(), solution, "Waiting and resuming retain the solution draft");
  assert.equal(state.intervention.nextReviewAt, null);
  await act("Pasar a comprobación", "Configuración corregida, verificar con el cliente"); await ready("Resolver intervención");
  await field("Comprobaciones realizadas").fill("Cliente realiza una venta y confirma el resultado");
  await field("Confirmado por (cliente o técnico)").fill("Responsable de tienda");
  await field("Responsable asignado").selectOption(assignees[0].id);
  await button("Guardar planificación").click(); await ready("Resolver intervención");
  assert.equal(await field("Comprobaciones realizadas").inputValue(), "Cliente realiza una venta y confirma el resultado", "Planning does not erase verification evidence");
  assert.equal(await field("Confirmado por (cliente o técnico)").inputValue(), "Responsable de tienda");
  await act("Resolver intervención", "Verificación satisfactoria con el responsable"); await ready("Reabrir intervención");
  assert.equal(state.ticket.status, "RESUELTO");
  assert.ok(!state.intervention.events.some(event => event.action === "START_REMOTE" || event.action === "START_ONSITE"), "SaaS resolution does not invent a remote connection or visit");
  await workflow.getByText("Atención cerrada · recuperación técnica pendiente", { exact: true }).waitFor();
  await workflow.getByRole("region", { name: "Cronología de la incidencia", exact: true }).waitFor();
  // A different first company makes the context regression observable.
  state.companies.unshift({ companyId: "10000000-0000-4000-8000-000000000099", companyName: "Otra empresa", taxId: "B00000099" });
  await panel.getByRole("button", { name: "Abrir lista de soporte", exact: true }).click();
  const card = page.locator(".ticket-card").filter({ hasText: "Intervención manual del fallo" });
  workflow = card.getByRole("region", { name: "Seguimiento de la incidencia", exact: true });
  await ready("Reabrir intervención");
  assert.equal(await page.locator(".company-ticket-selector select").inputValue(), companyId, "Referral selects linked company, not first company");
  await page.locator(".support-context-banner").getByRole("button", { name: "Volver al fallo original", exact: true }).click();
  workflow = panel.getByRole("region", { name: "Seguimiento de la incidencia", exact: true });
  await ready("Reabrir intervención");
  await panel.getByRole("button", { name: "Abrir lista de soporte", exact: true }).click();
  workflow = card.getByRole("region", { name: "Seguimiento de la incidencia", exact: true });
  await ready("Reabrir intervención");
  // General support must also retry ambiguous comment writes with the original key.
  const composer = card.getByLabel("Comentario", { exact: true });
  await composer.fill("Cliente confirma que la configuración ya funciona");
  state.loseCommentResponse = true;
  await card.getByRole("button", { name: "Añadir comentario", exact: true }).click();
  await card.getByRole("button", { name: "Reintentar comentario pendiente", exact: true }).click();
  await card.getByText("Cliente confirma que la configuración ya funciona", { exact: true }).waitFor();
  assert.equal(state.comments.length, 1);
  assert.deepEqual(state.commentPosts[0], state.commentPosts[1], "General support retry reuses original request ID and body");
  await act("Reabrir intervención", "Se detecta otro ajuste pendiente de revisar"); await ready("Trabajar desde SaaS");
  await act("Trabajar desde SaaS", "Comenzamos una nueva revisión de configuración"); await ready("Pasar a comprobación");
  await field("Próxima revisión (para dejar en espera)").fill("2099-01-02T10:00");
  await act("Esperar material", "Pendiente de recibir el adaptador de sustitución"); await ready("Retomar trabajo");
  assert.equal(state.intervention.status, "WAITING_MATERIAL");
  assert.equal(state.intervention.resumeStatus, "SAAS_IN_PROGRESS");
  const queue = page.locator(".support-ticket-filters select").first();
  await queue.selectOption("mine"); await card.waitFor();
  await queue.selectOption("unassigned"); await card.waitFor({ state: "detached" });
  await queue.selectOption("due"); assert.equal(await card.count(), 0, "Future waiting cases are not overdue");
  await queue.selectOption(""); await ready("Retomar trabajo");
  // Simulate time passing on the server without touching production data.
  state.intervention.nextReviewAt = "2020-01-01T10:00:00Z";
  state.ticket.nextReviewAt = state.intervention.nextReviewAt;
  await page.getByRole("button", { name: "Actualizar", exact: true }).click();
  await ready("Retomar trabajo"); await queue.selectOption("due"); await card.waitFor();
  await queue.selectOption("visits"); await card.waitFor({ state: "detached" });
  await queue.selectOption(""); await ready("Retomar trabajo");
  await act("Retomar trabajo", "Material disponible para coordinar la visita"); await ready("Pasar a comprobación");
  await act("Derivar a visita presencial", "Se requiere instalar el adaptador en tienda"); await ready("Iniciar visita presencial");
  await field("Fecha y hora de visita").fill("2099-01-03T11:00");
  await button("Guardar planificación").click(); await ready("Iniciar visita presencial");
  await queue.selectOption("visits"); await card.waitFor();
  assert.equal(state.intervention.assigneeUserId, assignees[0].id);
  await queue.selectOption("");
  await act("Iniciar visita presencial", "Técnico en tienda, comienza la instalación"); await ready("Pasar a comprobación");
  await field("Próxima revisión (para dejar en espera)").fill("2099-01-04T10:00");
  await act("Esperar al cliente", "Local cerrado temporalmente, cliente confirmará acceso"); await ready("Retomar trabajo");
  assert.equal(state.intervention.resumeStatus, "ONSITE_IN_PROGRESS", "Waiting during a visit remembers the visit phase");
  const output = fileURLToPath(new URL("../../output/playwright/", import.meta.url));
  await mkdir(output, { recursive: true });
  await workflow.locator(".intervention-heading").evaluate(el => el.scrollIntoView({ block: "start" }));
  await page.screenshot({ path: `${output}/saas-realistic-workflow.png` });
  await page.setViewportSize({ width: 900, height: 1100 });
  await workflow.locator(".intervention-heading").evaluate(el => el.scrollIntoView({ block: "start" }));
  await page.screenshot({ path: `${output}/saas-realistic-workflow-tablet.png` });
  await page.close();
  assert.deepEqual(errors, []);
  console.log("Realistic incident E2E passed: SaaS-only diagnosis/verification/closure, persistent drafts, real assignment, waits/resume, linked navigation/back, general-comment idempotency and unified chronology.");
} finally { await browser?.close(); server.kill(); }
