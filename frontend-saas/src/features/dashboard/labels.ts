export function useSummaryLabels() {
  const { language } = useI18n();
  const index = language === "zh" ? 2 : language === "en" ? 1 : 0;
  return (key: keyof typeof labels) => labels[key][index];
}

export function useSummaryCategoryLabel() {
  const l = useSummaryLabels();
  return (key: string) => Object.hasOwn(labels, key) ? l(key as keyof typeof labels) : key;
}
