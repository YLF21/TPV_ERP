export type WorkspaceLabelKey = keyof typeof labels;

export function useWorkspaceLabels() {
  const { language } = useI18n();
  return workspaceLabels(language);
}

export function workspaceLabels(language: string) {
  const index = language === "es" ? 0 : language === "en" ? 1 : 2;
  return (key: keyof typeof labels) => labels[key][index];
}
