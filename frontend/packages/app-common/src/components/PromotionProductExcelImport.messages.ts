export function promotionExcelMessage(
  locale: LocaleCode,
  key: keyof typeof messages.es,
  values?: Record<string, string | number>
) {
  const language = locale === "en" || locale === "zh" ? locale : "es";
  let result: string = messages[language][key];
  for (const [name, value] of Object.entries(values ?? {})) result = result.replace(`{${name}}`, String(value));
  return result;
}
